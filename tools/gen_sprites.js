#!/usr/bin/env node
// Generates rust/src/sprites.rs from the def() calls in web/art/*.js so the
// sprite ids and authoring sizes can never drift between Rust and JS.

const fs = require('fs');
const path = require('path');

const artDir = path.join(__dirname, '..', 'web', 'art');
const files = fs.readdirSync(artDir).filter(f => f.endsWith('.js')).sort();

const sprites = [];
const re = /^def\('([a-z0-9_]+)',\s*(\d+(?:\.\d+)?),\s*(\d+(?:\.\d+)?),/gm;
for (const f of files) {
  const src = fs.readFileSync(path.join(artDir, f), 'utf8');
  let m;
  while ((m = re.exec(src)) !== null) {
    sprites.push({ name: m[1], w: Number(m[2]), h: Number(m[3]) });
  }
}

const seen = new Set();
for (const s of sprites) {
  if (seen.has(s.name)) throw new Error('duplicate sprite name: ' + s.name);
  seen.add(s.name);
}

let out = `// @generated by tools/gen_sprites.js -- do not edit.
// Sprite ids match the insertion order of ART in web/art/*.js.
#![allow(dead_code)]

pub const SPRITE_COUNT: usize = ${sprites.length};

`;
sprites.forEach((s, i) => {
  out += `pub const S_${s.name.toUpperCase()}: u16 = ${i};\n`;
});

out += `\n/// Authoring size of each sprite, in atlas pixels.\npub const SPRITE_SIZE: [[f32; 2]; SPRITE_COUNT] = [\n`;
sprites.forEach(s => { out += `    [${s.w.toFixed(1)}, ${s.h.toFixed(1)}],\n`; });
out += `];\n
#[inline]
pub fn sprite_w(id: u16) -> f32 { SPRITE_SIZE[id as usize][0] }
#[inline]
pub fn sprite_h(id: u16) -> f32 { SPRITE_SIZE[id as usize][1] }
#[inline]
pub fn sprite_aspect(id: u16) -> f32 {
    let s = SPRITE_SIZE[id as usize];
    s[0] / s[1]
}
`;

const dest = path.join(__dirname, '..', 'rust', 'src', 'sprites.rs');
fs.writeFileSync(dest, out);
console.log(`generated ${sprites.length} sprites -> ${path.relative(process.cwd(), dest)}`);
